let total = 0, exact = 0, fuzzy = 0, zero = 0
const misses: Array<[string, string, string]> = []
for (const [cat, list] of SETS) {
  let cE = 0, cF = 0, cZ = 0
  for (const q of list) {
    total++
    const r = searchFoods(q, 'all', DISHES, [], [], [], DISH_MAP)
    const top = r[0] && r[0].kind === 'dish' ? r[0].dish.name : null
    if (!r.length) { zero++; cZ++; const g = guessDishFromName(q, INGREDIENTS); misses.push([cat, q, g ? '可猜食材:' + g.matched.join('+') : '猜不出']) }
    else if (top === q) { exact++; cE++ }
    else { fuzzy++; cF++; misses.push([cat, q, '→ ' + r.slice(0,2).map(x=>x.kind==='dish'?x.dish.name:x.food.name).join('、')]) }
  }
  const n = list.length
  console.log(`${cat.padEnd(10,'　')} ${String(n).padStart(3)} 项：精确 ${String(cE).padStart(3)}  近似 ${String(cF).padStart(2)}  零结果 ${String(cZ).padStart(2)}   命中率 ${((n-cZ)/n*100).toFixed(0)}%`)
}
console.log(`\n合计 ${total} 项：精确 ${exact} (${(exact/total*100).toFixed(0)}%)  近似 ${fuzzy}  零结果 ${zero} (${(zero/total*100).toFixed(0)}%)`)
console.log(`有结果率 ${((total-zero)/total*100).toFixed(0)}%\n`)
console.log('=== 零结果 ===')
for (const [c,q,d] of misses.filter(m=>m[2].startsWith('可猜')||m[2]==='猜不出')) console.log(`  [${c}] ${q.padEnd(10,'　')} ${d}`)
console.log('\n=== 非精确命中（看看对不对）===')
for (const [c,q,d] of misses.filter(m=>m[2].startsWith('→'))) console.log(`  [${c}] ${q.padEnd(10,'　')} ${d}`)
